"""Dataset thumbnail generation and serving.

Pure functions that produce ``<dataset_path>/.thumbnails/<edge>/<stem>.webp``
for each source media item. Parent-driven invalidation: thumbnails are deleted
and regenerated by callers whenever the source pixels change.

Images and GIFs go through Pillow. MP4 first-frame extraction uses PyAV
(imported lazily). AVIF input requires ``pillow-avif-plugin`` which
auto-registers with Pillow on import.
"""

from __future__ import annotations

import os
from pathlib import Path

import structlog

from app.core.dataset.media_types import VIDEO_EXTENSIONS

logger = structlog.get_logger(__name__)

# Register the AVIF Pillow plugin if available. The import has the
# side-effect of registering itself with Pillow's format registry.
try:
    import pillow_avif  # noqa: F401
except ImportError:
    pass

_THUMB_DIR_NAME = ".thumbnails"
_MAX_EDGE_DEFAULT = 256
_WEBP_QUALITY = 80
# Renditions a caller may ask for. The value lands in a PATH COMPONENT
# (`.thumbnails/<edge>/`), so it is an allowlist and not a range check:
# nothing outside this tuple ever reaches a path. Enforced in
# thumbnail_path_for, so the guarantee does not depend on the route asking.
#
# 256 is the original grid-tile size. The larger ones exist for library cards,
# which grow to ~(viewport-60)/6 and are then multiplied by the display's pixel
# ratio: 512 was measurably too soft on a real monitor, so the cover default is
# 1024 and 1536 is headroom for a wide card on a HiDPI display.
ALLOWED_MAX_EDGES = (256, 512, 1024, 1536)
# Every video/animation extension is first-frame extractable via PyAV
# (mp4/webm/mkv/avi decode; .gif's first frame works too), so the
# thumbnail path mirrors the canonical video set instead of an mp4-only
# literal that silently skipped webm/mkv/avi clips.
_VIDEO_EXTS = VIDEO_EXTENSIONS


def thumbnail_dir(dataset_path: str) -> Path:
    """Return the per-dataset thumbnail directory (does not create it)."""
    return Path(dataset_path) / _THUMB_DIR_NAME


def _flat_stem(rel_path: str) -> str:
    """Return the flattened stem of ``rel_path`` (no size, no extension).

    ``rel_path`` may use forward slashes or OS separators. Subdirectory
    sources (e.g. ``control/img1.jpg``) prefix their dir components
    (``control__img1``) so a control image can't collide with the root
    image of the same stem, and so no separator from *rel_path* ever
    survives into a path component of ours.
    """
    p = Path(rel_path.replace("\\", "/"))
    return "__".join((*p.parent.parts, p.stem)) if p.parent.parts else p.stem


def thumbnail_path_for(
    dataset_path: str, rel_path: str, max_edge: int = _MAX_EDGE_DEFAULT,
) -> Path:
    """Return the absolute path of the thumbnail for ``rel_path``.

    Layout is ``.thumbnails/<edge>/<stem>.webp``: the rendition size is a
    DIRECTORY, never part of the filename. It used to be a ``@<edge>``
    suffix on the stem, and ``@`` is a legal filename character — so
    ``foo.png`` at 512 and ``foo@512.png`` at the default size both
    resolved to ``foo@512.webp``: one file served two sources and
    invalidating either deleted the other's cache. A derived filename is a
    namespace; the only separator safe to encode a key with is one the
    source alphabet cannot produce, and a path separator is exactly that
    (no single path component may contain one).

    *max_edge* becomes a path component, so it is allowlisted here as well
    as at the route: an arbitrary integer never reaches a path.
    """
    if max_edge not in ALLOWED_MAX_EDGES:
        raise ValueError(
            f"max_edge {max_edge!r} is not one of {list(ALLOWED_MAX_EDGES)}",
        )
    return thumbnail_dir(dataset_path) / str(max_edge) / f"{_flat_stem(rel_path)}.webp"


def _legacy_thumbnail_paths(dataset_path: str, rel_path: str) -> list[Path]:
    """Return this source's renditions under the PRE-``<edge>/`` flat layout.

    The old scheme wrote ``.thumbnails/<stem>.webp`` for the default size and
    ``.thumbnails/<stem>@<edge>.webp`` for the others. Those names are
    enumerated literally from :data:`ALLOWED_MAX_EDGES` — never globbed and
    never matched against a directory listing — because a source filename may
    legitimately contain ``[``, ``*`` or ``?``, which a glob would interpret
    instead of match, and ``@``, which a prefix scan would mis-attribute.

    Included in invalidation so a churned item cleans up its own orphans;
    whole-dataset cleanup is :func:`purge_legacy_layout`.
    """
    root = thumbnail_dir(dataset_path)
    stem = _flat_stem(rel_path)
    return [root / f"{stem}.webp"] + [
        root / f"{stem}@{edge}.webp"
        for edge in ALLOWED_MAX_EDGES
        if edge != _MAX_EDGE_DEFAULT
    ]


def thumbnail_paths_for(dataset_path: str, rel_path: str) -> list[Path]:
    """Return EVERY rendition of ``rel_path``'s thumbnail, at any size.

    Invalidation is what this exists for: a source whose pixels changed must
    drop all of its derived sizes, or a card keeps painting pre-edit pixels
    at whichever size it happens to request.

    The per-size directories make the sibling set explicit — one path per
    allowed edge, computed, not discovered — so this neither lists a
    directory nor pattern-matches a filename, and cannot reach a neighbour's
    file whatever characters its name contains. Legacy flat-layout names are
    appended so an upgraded dataset drops its stale renditions too.
    """
    return [
        thumbnail_path_for(dataset_path, rel_path, edge)
        for edge in ALLOWED_MAX_EDGES
    ] + _legacy_thumbnail_paths(dataset_path, rel_path)


def _iter_legacy_entries(dataset_path: str) -> "list[os.DirEntry[str]]":
    """Return the flat-layout rendition entries directly inside ``.thumbnails/``.

    The single definition of "this dataset has not been migrated yet". Both
    :func:`legacy_layout_survey` (what the user is told) and
    :func:`purge_legacy_layout` (what is actually deleted) enumerate through
    here, so the count on the button and the count that is removed cannot
    drift into promising a reclaim that does not happen.

    ONE non-recursive ``scandir`` of a single directory: every live rendition
    is one level deeper in ``<edge>/``, so nothing about the dataset's own
    tree — which may hold tens of thousands of media files — is ever read.
    That is what makes detection cheap enough to run for every dataset in the
    library on one request.

    Returns ``[]`` when there is no cache directory or it cannot be listed.
    """
    root = thumbnail_dir(dataset_path)
    try:
        # `with` so the directory handle is released even on a mid-iteration
        # error (D10: every resource released in finally).
        with os.scandir(root) as it:
            entries = list(it)
    except OSError:
        # Missing directory is the common case (never-thumbnailed dataset) and
        # is not worth a log line; a genuine permission error surfaces at the
        # purge, which does log.
        return []
    return [
        e for e in entries
        if (e.name.endswith(".webp") or e.name.endswith(".webp.tmp"))
        and e.is_file(follow_symlinks=False)
    ]


def legacy_layout_survey(dataset_path: str) -> tuple[int, int]:
    """Return ``(file_count, total_bytes)`` of this dataset's flat renditions.

    Detection half of the migration off the pre-``<edge>/`` layout. ``(0, 0)``
    means the dataset is already migrated (or never had a cache) — that is the
    value the caller uses to leave it alone, so it must be reachable without a
    scan of any kind.

    Read-only and side-effect free: a survey that repaired what it found could
    not be run from a GET.
    """
    files = _iter_legacy_entries(dataset_path)
    total = 0
    for entry in files:
        try:
            total += entry.stat().st_size
        except OSError:
            # Vanished between listing and stat — count the file, not its size.
            pass
    return len(files), total


def purge_legacy_layout(dataset_path: str) -> int:
    """Delete flat-layout renditions left behind by the pre-``<edge>/`` scheme.

    Only files DIRECTLY inside ``.thumbnails/`` are removed; every current
    rendition lives one level deeper in ``<edge>/``, so this cannot touch a
    live cache. Called once per dataset scan — the orphans go away on the
    first scan after the upgrade instead of accumulating forever, and the
    renditions the user still looks at are regenerated on demand.

    This IS the whole migration, and unlinking is all of it: nothing reads a
    flat rendition any more (``thumbnail_path_for`` cannot name one), so the
    pixels served were already correct and no rehash, rescore or rescan is
    implied. `app/api/dataset/thumbnail_routes.py` drives it across the
    library for datasets that are never scanned again.

    Returns the number of files removed (0 when there is nothing to do).
    """
    root = thumbnail_dir(dataset_path)
    removed = 0
    for entry in _iter_legacy_entries(dataset_path):
        try:
            os.unlink(entry.path)
            removed += 1
        except OSError as e:
            logger.warning(
                "thumbnail_legacy_purge_failed", path=entry.path, error=str(e),
            )
    if removed:
        logger.info("thumbnail_legacy_layout_purged", path=str(root), removed=removed)
    return removed


def generate_thumbnail(
    src_path: str,
    dst_path: Path,
    max_edge: int = _MAX_EDGE_DEFAULT,
) -> bool:
    """Generate a thumbnail at *dst_path* from *src_path*.

    Writes to ``<dst>.tmp`` first then atomically renames, so concurrent
    readers never observe a partially written file. Returns ``True`` on
    success, ``False`` if the source could not be decoded (logged).
    """
    from PIL import Image

    dst_path.parent.mkdir(parents=True, exist_ok=True)

    ext = Path(src_path).suffix.lower()
    tmp_path = dst_path.with_suffix(dst_path.suffix + ".tmp")

    try:
        if ext in _VIDEO_EXTS:
            img = _first_video_frame(src_path)
            if img is None:
                return False
        else:
            with Image.open(src_path) as opened:
                img = opened.convert("RGB").copy()

        img.thumbnail((max_edge, max_edge))
        img.save(tmp_path, "WEBP", quality=_WEBP_QUALITY)
        os.replace(tmp_path, dst_path)
        return True
    except Exception as e:  # noqa: BLE001
        logger.warning("thumbnail_generation_failed", path=src_path, error=str(e))
        # Best-effort cleanup of orphan temp file
        try:
            if tmp_path.exists():
                tmp_path.unlink()
        except OSError:
            pass
        return False


def _first_video_frame(src_path: str):
    """Return a PIL Image of the first decodable frame, or None."""
    try:
        import av  # type: ignore
        from PIL import Image
    except ImportError:
        logger.warning("thumbnail_video_skip_no_pyav", path=src_path)
        return None

    try:
        with av.open(src_path) as container:
            stream = container.streams.video[0]
            for frame in container.decode(stream):
                return Image.fromarray(frame.to_ndarray(format="rgb24"))
    except Exception as e:  # noqa: BLE001
        logger.warning("thumbnail_video_decode_failed", path=src_path, error=str(e))
    return None


def ensure_thumbnail(
    dataset_path: str, rel_path: str, max_edge: int = _MAX_EDGE_DEFAULT,
) -> Path | None:
    """Return an existing thumbnail or generate one at *max_edge*.

    Returns ``None`` when the source is missing or unreadable.
    """
    src_path = os.path.join(dataset_path, rel_path)
    dst_path = thumbnail_path_for(dataset_path, rel_path, max_edge)

    if dst_path.exists():
        return dst_path
    if not os.path.exists(src_path):
        return None
    if generate_thumbnail(src_path, dst_path, max_edge):
        return dst_path
    return None


def invalidate_thumbnail(dataset_path: str, rel_path: str) -> None:
    """Delete every rendition of *rel_path*'s thumbnail (best-effort).

    All sizes, not just the default one — see :func:`thumbnail_paths_for`.
    """
    for dst_path in thumbnail_paths_for(dataset_path, rel_path):
        try:
            dst_path.unlink(missing_ok=True)
        except OSError as e:
            logger.warning(
                "thumbnail_invalidate_failed", path=str(dst_path), error=str(e),
            )


def delete_thumbnail(dataset_path: str, rel_path: str) -> None:
    """Alias of :func:`invalidate_thumbnail`, used at deletion call sites."""
    invalidate_thumbnail(dataset_path, rel_path)
